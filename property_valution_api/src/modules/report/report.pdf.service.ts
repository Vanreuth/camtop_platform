const PDFDocument = require("pdfkit");

type PdfAlignment = "left" | "center" | "right";

export type PdfReportColumn = {
  key: string;
  label: string;
  width: number;
  align?: PdfAlignment;
};

type CreateTablePdfInput = {
  title: string;
  subtitle: string;
  summary?: string;
  generatedAt: Date;
  generatedBy: string;
  columns: PdfReportColumn[];
  rows: Array<Record<string, unknown>>;
};

const COLORS = {
  title: "#0F172A",
  subtitle: "#475569",
  border: "#CBD5E1",
  headerBg: "#E2E8F0",
  headerText: "#0F172A",
  rowText: "#111827",
  muted: "#64748B",
  chipBg: "#F8FAFC",
} as const;

const PAGE = {
  size: "A4",
  layout: "landscape",
  margin: 36,
  rowHeight: 24,
  headerHeight: 26,
  footerSpace: 28,
} as const;

const formatDateTime = (value: Date) =>
  value.toLocaleString("en-US", {
    year: "numeric",
    month: "short",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });

const toCellText = (value: unknown) => {
  if (value === null || value === undefined || value === "") {
    return "-";
  }

  if (value instanceof Date) {
    return formatDateTime(value);
  }

  return String(value);
};

const truncateText = (value: string, maxLength = 42) =>
  value.length > maxLength ? `${value.slice(0, maxLength - 3).trimEnd()}...` : value;

export const createTablePdfBuffer = async (
  input: CreateTablePdfInput,
): Promise<Buffer> => {
  const doc = new PDFDocument({
    size: PAGE.size,
    layout: PAGE.layout,
    margin: PAGE.margin,
    bufferPages: true,
  });

  const chunks: Buffer[] = [];
  doc.on("data", (chunk: Buffer) => chunks.push(chunk));

  const done = new Promise<Buffer>((resolve, reject) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });

  const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
  const pageBottom = doc.page.height - doc.page.margins.bottom - PAGE.footerSpace;

  let cursorY = doc.page.margins.top;

  const drawPageHeader = () => {
    cursorY = doc.page.margins.top;

    doc
      .font("Helvetica-Bold")
      .fontSize(18)
      .fillColor(COLORS.title)
      .text(input.title, doc.page.margins.left, cursorY, {
        width: pageWidth,
      });

    cursorY += 24;

    doc
      .font("Helvetica")
      .fontSize(10)
      .fillColor(COLORS.subtitle)
      .text(input.subtitle, doc.page.margins.left, cursorY, {
        width: pageWidth,
      });

    cursorY += 22;

    const infoText = `Generated by ${input.generatedBy} on ${formatDateTime(input.generatedAt)}`;
    doc
      .roundedRect(doc.page.margins.left, cursorY, pageWidth, 24, 6)
      .fillAndStroke(COLORS.chipBg, COLORS.border);
    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor(COLORS.subtitle)
      .text(infoText, doc.page.margins.left + 10, cursorY + 7, {
        width: pageWidth - 20,
      });

    cursorY += 34;

    if (input.summary) {
      doc
        .font("Helvetica")
        .fontSize(9)
        .fillColor(COLORS.muted)
        .text(input.summary, doc.page.margins.left, cursorY, {
          width: pageWidth,
        });
      cursorY += 24;
    }
  };

  const drawTableHeader = () => {
    let cellX = doc.page.margins.left;

    doc
      .rect(cellX, cursorY, pageWidth, PAGE.headerHeight)
      .fillAndStroke(COLORS.headerBg, COLORS.border);

    input.columns.forEach((column) => {
      doc
        .font("Helvetica-Bold")
        .fontSize(9)
        .fillColor(COLORS.headerText)
        .text(column.label, cellX + 6, cursorY + 8, {
          width: column.width - 12,
          align: column.align ?? "left",
          ellipsis: true,
        });

      doc
        .moveTo(cellX, cursorY)
        .lineTo(cellX, cursorY + PAGE.headerHeight)
        .strokeColor(COLORS.border)
        .stroke();

      cellX += column.width;
    });

    doc
      .moveTo(doc.page.margins.left + pageWidth, cursorY)
      .lineTo(doc.page.margins.left + pageWidth, cursorY + PAGE.headerHeight)
      .strokeColor(COLORS.border)
      .stroke();

    cursorY += PAGE.headerHeight;
  };

  const ensureSpace = (requiredHeight: number, includeTableHeader = false) => {
    if (cursorY + requiredHeight <= pageBottom) {
      return;
    }

    doc.addPage({
      size: PAGE.size,
      layout: PAGE.layout,
      margin: PAGE.margin,
    });
    drawPageHeader();

    if (includeTableHeader) {
      drawTableHeader();
    }
  };

  drawPageHeader();
  drawTableHeader();

  input.rows.forEach((row) => {
    ensureSpace(PAGE.rowHeight, true);

    let cellX = doc.page.margins.left;

    doc
      .rect(cellX, cursorY, pageWidth, PAGE.rowHeight)
      .fillAndStroke("#FFFFFF", COLORS.border);

    input.columns.forEach((column) => {
      const value = truncateText(toCellText(row[column.key]));

      doc
        .font("Helvetica")
        .fontSize(8.5)
        .fillColor(COLORS.rowText)
        .text(value, cellX + 6, cursorY + 7, {
          width: column.width - 12,
          align: column.align ?? "left",
          ellipsis: true,
        });

      doc
        .moveTo(cellX, cursorY)
        .lineTo(cellX, cursorY + PAGE.rowHeight)
        .strokeColor(COLORS.border)
        .stroke();

      cellX += column.width;
    });

    doc
      .moveTo(doc.page.margins.left + pageWidth, cursorY)
      .lineTo(doc.page.margins.left + pageWidth, cursorY + PAGE.rowHeight)
      .strokeColor(COLORS.border)
      .stroke();

    cursorY += PAGE.rowHeight;
  });

  const pageRange = doc.bufferedPageRange();
  for (let pageIndex = 0; pageIndex < pageRange.count; pageIndex += 1) {
    doc.switchToPage(pageIndex);
    doc
      .font("Helvetica")
      .fontSize(8)
      .fillColor(COLORS.muted)
      .text(
        `Page ${pageIndex + 1} of ${pageRange.count}`,
        doc.page.margins.left,
        doc.page.height - doc.page.margins.bottom + 6,
        {
          width: pageWidth,
          align: "right",
        },
      );
  }

  doc.end();
  return done;
};
